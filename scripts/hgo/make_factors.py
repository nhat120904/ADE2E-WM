"""Factor table of every training window (pilot logs) and every navtest scene, plus combination counts, so held-out
combinations can be chosen before any model is trained (docs/METHOD.md).

usage: python scripts/hgo/make_factors.py  ->  data/_lists/hgo_factors_{train,val,test}.csv, docs/hgo_factor_counts.md
"""

import itertools
import os
from multiprocessing import Pool
from pathlib import Path

import pandas as pd

from ade2e_wm.hgo.data import LogData
from ade2e_wm.hgo.splits import factors

ROOT = Path(__file__).resolve().parents[2]
SETS = {"train": ("phase1_train_logs.txt", "trainval", None), "val": ("phase1_val_logs.txt", "trainval", None),
        "test": ("phase1_test_logs.txt", "test", "navtest_tokens.txt")}


def one(args):
    log, split, toks = args
    ld = LogData(ROOT / f"data/navsim_logs/{split}/{log}.pkl", ROOT / f"data/sensor_blobs/{split}")
    rows = []
    for t in ld.windows((2, 4, 8), toks, need_future_images=(split != "test")):
        rows.append({"token": ld.token[t], "log": log, **factors(ld, t)})
    return rows


def main():
    os.chdir(ROOT)
    lists = ROOT / "data/_lists"
    md = ["# HGO factor counts (generated by scripts/hgo/make_factors.py)", ""]
    for name, (lf, split, tf) in SETS.items():
        logs = (lists / lf).read_text().split()
        toks = set((lists / tf).read_text().split()) if tf else None
        with Pool(16) as p:
            rows = [r for rs in p.map(one, [(l, split, toks) for l in logs]) for r in rs]
        df = pd.DataFrame(rows)
        df.to_csv(lists / f"hgo_factors_{name}.csv", index=False)
        md += [f"## {name}: {len(df)} samples, {df['log'].nunique()} logs", ""]
        c = df.groupby(["maneuver", "vru", "density"]).size().unstack("density").fillna(0).astype(int)
        md += ["```", c.to_string(), "```", ""]
    (ROOT / "docs/hgo_factor_counts.md").write_text("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
