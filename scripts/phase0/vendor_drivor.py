"""Vendor DrivoR's NAVSIM agent into ade2e_wm for evaluation with the official NAVSIM v2.2 devkit.

DrivoR is built on NAVSIM v1; its authors evaluate Nav2 by copying the agent into the v2 repo
(valeoai/DrivoR#13). To keep both upstream checkouts untouched, this copies the agent at a pinned
commit into src/ade2e_wm/agents/drivor and applies only:
  1. package path rewrite  navsim.agents.drivoR -> ade2e_wm.agents.drivor
  2. NAVSIM v2 AbstractAgent API: accept `trajectory_sampling` and pass it to super().__init__
     (the change prescribed in valeoai/DrivoR#13).
Re-run this script to regenerate the vendored copy; it refuses to run on a different commit.
"""

import re
import shutil
import subprocess
from pathlib import Path

PROJECT = Path(__file__).resolve().parents[2]
UPSTREAM = PROJECT / "third_party/DrivoR"
PINNED_COMMIT = "fc6e5aa144bbcb5a046e22c18f1bd5cf3af8634a"
SRC = UPSTREAM / "navsim/agents/drivoR"
DST = PROJECT / "src/ade2e_wm/agents/drivor"

head = subprocess.check_output(["git", "-C", str(UPSTREAM), "rev-parse", "HEAD"], text=True).strip()
assert head == PINNED_COMMIT, f"DrivoR checkout is at {head}, expected {PINNED_COMMIT}"

if DST.exists():
    shutil.rmtree(DST)
shutil.copytree(SRC, DST, ignore=shutil.ignore_patterns("__pycache__"))
for d in [DST, *[p for p in DST.rglob("*") if p.is_dir()]]:
    (d / "__init__.py").touch(exist_ok=True)

n_rewrites = 0
for py in DST.rglob("*.py"):
    text = py.read_text()
    new = text.replace("navsim.agents.drivoR", "ade2e_wm.agents.drivor")
    n_rewrites += text.count("navsim.agents.drivoR")
    py.write_text(new)

agent = DST / "drivor_agent.py"
text = agent.read_text()
old_sig = "            num_gpus: int = 1,\n    ):\n        super().__init__()\n"
new_sig = (
    "            num_gpus: int = 1,\n"
    "            trajectory_sampling: TrajectorySampling = None,  # ade2e_wm: NAVSIM v2 API (DrivoR#13)\n"
    "    ):\n"
    "        if trajectory_sampling is None:\n"
    "            trajectory_sampling = TrajectorySampling(time_horizon=4, interval_length=0.5)\n"
    "        super().__init__(trajectory_sampling)\n"
)
assert text.count(old_sig) == 1, "DrivoRAgent.__init__ signature changed upstream; update the patch"
text = text.replace(old_sig, new_sig)
text = "from nuplan.planning.simulation.trajectory.trajectory_sampling import TrajectorySampling  # ade2e_wm\n" + text
agent.write_text(text)

(DST / "VENDORED_FROM.txt").write_text(
    f"Source: https://github.com/valeoai/DrivoR/tree/{PINNED_COMMIT}/navsim/agents/drivoR\n"
    f"Generated by scripts/phase0/vendor_drivor.py\n"
    f"Patches: package path rewrite ({n_rewrites} occurrences); trajectory_sampling arg (DrivoR#13).\n"
)
print(f"vendored {sum(1 for _ in DST.rglob('*.py'))} files to {DST}, {n_rewrites} path rewrites")
